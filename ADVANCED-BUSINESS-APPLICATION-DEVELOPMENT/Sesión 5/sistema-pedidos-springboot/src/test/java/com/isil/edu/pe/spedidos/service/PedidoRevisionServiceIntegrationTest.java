package com.isil.edu.pe.spedidos.service;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertFalse;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import com.isil.edu.pe.spedidos.entity.Pedido;
import com.isil.edu.pe.spedidos.exception.PedidoRevisionException;
import com.isil.edu.pe.spedidos.repository.PedidoRepository;
import java.math.BigDecimal;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.dao.DataAccessException;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;

@SpringBootTest
@ActiveProfiles("test")
class PedidoRevisionServiceIntegrationTest {

    @Autowired private PedidoRevisionService service;
    @Autowired private PedidoRepository pedidoRepository;
    @Autowired private JdbcTemplate jdbc;

    @BeforeEach
    void preparar() {
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS pedido_revision (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    pedido_id BIGINT NOT NULL UNIQUE,
                    observacion VARCHAR(500) NOT NULL,
                    fecha_revision TIMESTAMP NOT NULL,
                    FOREIGN KEY (pedido_id) REFERENCES pedido(id)
                )
                """);
        limpiar();
    }

    @AfterEach
    void terminar() {
        limpiar();
    }

    private void limpiar() {
        jdbc.update("DELETE FROM pedido_revision");
        pedidoRepository.deleteAll();
    }

    private long crearPedido() {
        Pedido pedido = new Pedido("Ana Torres", "LAP-001", "Laptop",
                new BigDecimal("100.00"), 2, new BigDecimal("200.00"));
        return pedidoRepository.saveAndFlush(pedido).getId();
    }

    private boolean revisado(long id) {
        return Boolean.TRUE.equals(jdbc.queryForObject(
                "SELECT revisado FROM pedido WHERE id = ?", Boolean.class, id));
    }

    private int totalRevisiones(long id) {
        return jdbc.queryForObject("SELECT COUNT(*) FROM pedido_revision WHERE pedido_id = ?", Integer.class, id);
    }

    @Test
    void confirmaAmbasEscriturasEnRevisionValida() {
        long id = crearPedido();

        service.revisarPedido(id, "Verificado por el operador");

        assertTrue(revisado(id));
        assertEquals(1, totalRevisiones(id));
        assertEquals("Verificado por el operador", jdbc.queryForObject(
                "SELECT observacion FROM pedido_revision WHERE pedido_id = ?", String.class, id));
    }

    @Test
    void revierteUpdateCuandoInsertFalla() {
        long id = crearPedido();
        String observacionExcesiva = "X".repeat(600);

        assertThrows(DataAccessException.class,
                () -> service.revisarPedido(id, observacionExcesiva));

        assertFalse(revisado(id));
        assertEquals(0, totalRevisiones(id));
    }

    @Test
    void rechazaSegundaRevisionSinDuplicarFilas() {
        long id = crearPedido();
        service.revisarPedido(id, "Primera revisión");

        PedidoRevisionException error = assertThrows(PedidoRevisionException.class,
                () -> service.revisarPedido(id, "Segunda revisión"));

        assertEquals(409, error.getEstado().value());
        assertTrue(revisado(id));
        assertEquals(1, totalRevisiones(id));
    }

    @Test
    void rechazaObservacionVaciaSinEscribir() {
        long id = crearPedido();

        PedidoRevisionException error = assertThrows(PedidoRevisionException.class,
                () -> service.revisarPedido(id, "   "));

        assertEquals(400, error.getEstado().value());
        assertFalse(revisado(id));
        assertEquals(0, totalRevisiones(id));
    }

    @Test
    void rechazaIdInexistenteSinEscribir() {
        PedidoRevisionException error = assertThrows(PedidoRevisionException.class,
                () -> service.revisarPedido(999999L, "Comprobación"));
        assertEquals(404, error.getEstado().value());
    }
}
