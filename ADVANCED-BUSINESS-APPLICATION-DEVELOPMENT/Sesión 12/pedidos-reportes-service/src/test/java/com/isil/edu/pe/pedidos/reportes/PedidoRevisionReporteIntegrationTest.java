package com.isil.edu.pe.pedidos.reportes;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertTrue;
import static org.springframework.test.web.servlet.request.MockMvcRequestBuilders.get;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.jsonPath;
import static org.springframework.test.web.servlet.result.MockMvcResultMatchers.status;

import com.isil.edu.pe.pedidos.reportes.repository.PedidoRevisionReporteJdbcRepository;
import java.math.BigDecimal;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.test.context.ActiveProfiles;
import org.springframework.test.web.servlet.MockMvc;
import org.springframework.test.web.servlet.setup.MockMvcBuilders;
import org.springframework.web.context.WebApplicationContext;

@SpringBootTest
@ActiveProfiles("test")
class PedidoRevisionReporteIntegrationTest {

    @Autowired private JdbcTemplate jdbc;
    @Autowired private PedidoRevisionReporteJdbcRepository repository;
    @Autowired private WebApplicationContext context;
    private MockMvc mvc;

    @BeforeEach
    void preparar() {
        mvc = MockMvcBuilders.webAppContextSetup(context).build();
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS pedido (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    cliente VARCHAR(120) NOT NULL,
                    producto_codigo VARCHAR(30) NOT NULL,
                    producto_nombre VARCHAR(120) NOT NULL,
                    precio_unitario DECIMAL(12,2) NOT NULL,
                    cantidad INT NOT NULL,
                    total DECIMAL(12,2) NOT NULL,
                    fecha TIMESTAMP NOT NULL,
                    revisado BOOLEAN NOT NULL DEFAULT FALSE
                )
                """);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS pedido_revision (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    pedido_id BIGINT NOT NULL UNIQUE,
                    observacion VARCHAR(500) NOT NULL,
                    fecha_revision TIMESTAMP NOT NULL,
                    FOREIGN KEY (pedido_id) REFERENCES pedido(id)
                )
                """);
        limpiar();
        jdbc.update("""
                INSERT INTO pedido (id, cliente, producto_codigo, producto_nombre,
                                    precio_unitario, cantidad, total, fecha, revisado)
                VALUES (101, 'Ana', 'LAP', 'Laptop', 100.00, 1, 100.00, CURRENT_TIMESTAMP, TRUE)
                """);
        jdbc.update("""
                INSERT INTO pedido (id, cliente, producto_codigo, producto_nombre,
                                    precio_unitario, cantidad, total, fecha, revisado)
                VALUES (102, 'Luis', 'MON', 'Monitor', 200.00, 2, 400.00, CURRENT_TIMESTAMP, FALSE)
                """);
        jdbc.update("""
                INSERT INTO pedido_revision (pedido_id, observacion, fecha_revision)
                VALUES (101, 'Verificado', CURRENT_TIMESTAMP)
                """);
    }

    @AfterEach
    void terminar() {
        limpiar();
    }

    private void limpiar() {
        jdbc.update("DELETE FROM pedido_revision");
        jdbc.update("DELETE FROM pedido");
    }

    @Test
    void filtradoJdbcRetornaSoloPedidosRevisados() {
        var revisados = repository.listarRevisiones(true);
        assertEquals(1, revisados.size());
        assertEquals(101L, revisados.getFirst().id());
        assertEquals("Verificado", revisados.getFirst().observacion());
    }

    @Test
    void resumenJdbcCalculaPorcentajesCorrectos() {
        var resumen = repository.obtenerResumen();
        assertEquals(2, resumen.totalPedidos());
        assertEquals(1, resumen.totalRevisados());
        assertEquals(1, resumen.totalPendientes());
        assertEquals(0, new BigDecimal("50.00").compareTo(resumen.porcentajeRevisado()));
    }

    @Test
    void apiRevisionesEntregaJson() throws Exception {
        mvc.perform(get("/api/v1/pedidos/revisiones").param("estado", "REVISADO"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$[0].id").value(101))
                .andExpect(jsonPath("$[0].observacion").value("Verificado"));
    }

    @Test
    void apiRechazaEstadoInvalidoCon400() throws Exception {
        mvc.perform(get("/api/v1/pedidos/revisiones").param("estado", "CERRADO"))
                .andExpect(status().isBadRequest());
    }

    @Test
    void apiEstadisticasEntregaJson() throws Exception {
        mvc.perform(get("/api/v1/pedidos/estadisticas/revisiones"))
                .andExpect(status().isOk())
                .andExpect(jsonPath("$.totalPedidos").value(2))
                .andExpect(jsonPath("$.totalRevisados").value(1))
                .andExpect(jsonPath("$.totalPendientes").value(1));
    }
}
